// ===== SCROLL ANIMATIONS =====
const revealObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) {
            entry.target.classList.add('visible');
            revealObserver.unobserve(entry.target);
        }
    });
}, { threshold: 0.12 });

function initReveal() {
    const elements = document.querySelectorAll('.step-card, .why-card, .quote-card, .booking-card, .section-header, .hero-content');
    elements.forEach((el, i) => {
        el.classList.add('reveal');
        if (i % 3 === 1) el.classList.add('delay-1');
        if (i % 3 === 2) el.classList.add('delay-2');
        revealObserver.observe(el);
    });
}

// ===== NAVBAR SCROLL =====
function initNavbar() {
    const navbar = document.getElementById('navbar');
    window.addEventListener('scroll', () => {
        if (window.scrollY > 50) {
            navbar.classList.add('scrolled');
        } else {
            navbar.classList.remove('scrolled');
        }
    });
}

// ===== MOBILE MENU =====
function toggleMenu() {
    const navLinks = document.getElementById('navLinks');
    navLinks.classList.toggle('open');
}

// Close mobile menu on link click
document.querySelectorAll('.nav-links a').forEach(link => {
    link.addEventListener('click', () => {
        document.getElementById('navLinks').classList.remove('open');
    });
});

// ===== TOAST NOTIFICATION =====
function showToast(msg, type = 'info') {
    const existing = document.querySelector('.toast');
    if (existing) existing.remove();

    const toast = document.createElement('div');
    toast.className = `toast toast-${type}`;
    toast.textContent = msg;
    toast.style.cssText = `
        position: fixed; bottom: 2rem; left: 50%; transform: translateX(-50%);
        background: ${type === 'error' ? '#DC2626' : '#16A34A'};
        color: white; padding: 1rem 2rem; border-radius: 9999px;
        font-family: Outfit, sans-serif; font-weight: 600; font-size: 0.95rem;
        z-index: 9999; box-shadow: 0 8px 30px rgba(0,0,0,0.4);
        animation: fadeInUp 0.3s ease;
    `;
    document.body.appendChild(toast);
    setTimeout(() => toast.remove(), 4000);
}

// ===== SMOOTH ANCHOR SCROLL =====
document.querySelectorAll('a[href^="#"]').forEach(anchor => {
    anchor.addEventListener('click', function(e) {
        const href = this.getAttribute('href');
        if (href === '#') return;
        const target = document.querySelector(href);
        if (target) {
            e.preventDefault();
            const navH = document.getElementById('navbar').offsetHeight;
            const top = target.getBoundingClientRect().top + window.scrollY - navH;
            window.scrollTo({ top, behavior: 'smooth' });
        }
    });
});

// ===== SET MIN DATE FOR BOOKING =====
function initDateMin() {
    const dateInput = document.getElementById('bookDate');
    if (dateInput) {
        const today = new Date().toISOString().split('T')[0];
        dateInput.min = today;
    }
}

// ===== INIT =====
document.addEventListener('DOMContentLoaded', () => {
    applyTranslations();
    initReveal();
    initNavbar();
    initDateMin();
});
